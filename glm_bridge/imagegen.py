"""Image generation via the upstream /image endpoint, exposed as OpenAI
/v1/images/generations and /v1/images/edits.

The upstream response shape is not documented, so results are extracted
tolerantly: an image/* body, data URLs, http(s) image URLs or base64 fields
anywhere in a JSON body. Generated bytes are served back from a small
in-memory cache with unguessable URLs when the client asks for ``url`` output.
"""

from __future__ import annotations

import base64
import binascii
import re
import secrets
import time
from collections import OrderedDict
from typing import Any

import httpx

from .config import Settings
from .errors import BridgeError, bad_request
from .images import ImageFetcher, sniff_mime
from .upstream import GLMChatClient, NonceRejected, describe_upstream_body

_URL_KEYS = {"url", "image", "image_url", "imageurl", "src", "link", "output", "file"}
_B64_KEYS = {"b64_json", "b64", "base64", "image_base64", "data", "image"}
_IMG_EXT = re.compile(r"\.(png|jpe?g|webp|gif)(\?|$)", re.I)


class ImageStore:
    def __init__(self, ttl: float, max_items: int) -> None:
        self.ttl = ttl
        self.max_items = max(1, max_items)
        self._items: OrderedDict[str, tuple[float, str, bytes]] = OrderedDict()

    def put(self, raw: bytes, mime: str) -> str:
        self._evict()
        token = secrets.token_urlsafe(24)
        self._items[token] = (time.monotonic() + self.ttl, mime, raw)
        while len(self._items) > self.max_items:
            self._items.popitem(last=False)
        return token

    def get(self, token: str) -> tuple[str, bytes] | None:
        self._evict()
        item = self._items.get(token)
        return None if item is None else (item[1], item[2])

    def _evict(self) -> None:
        now = time.monotonic()
        for token in [t for t, (exp, _, _) in self._items.items() if exp < now]:
            del self._items[token]


def _b64_image(value: str) -> bytes | None:
    try:
        raw = base64.b64decode(re.sub(r"\s+", "", value), validate=True)
    except (binascii.Error, ValueError):
        return None
    return raw if sniff_mime(raw) else None


def extract_images(resp: httpx.Response) -> list[tuple[str, Any]]:
    """-> list of ("bytes", raw) or ("url", url)."""
    ctype = resp.headers.get("content-type", "").lower()
    if ctype.startswith("image/"):
        return [("bytes", resp.content)] if sniff_mime(resp.content) else []
    try:
        obj = resp.json()
    except ValueError:
        obj = resp.text.strip()
    found: list[tuple[str, Any]] = []

    def walk(node: Any, key: str | None) -> None:
        if isinstance(node, str):
            if node.startswith("data:image/") and ";base64," in node:
                raw = _b64_image(node.split(",", 1)[1])
                if raw:
                    found.append(("bytes", raw))
            elif node.startswith(("http://", "https://")) and (key in _URL_KEYS or _IMG_EXT.search(node)):
                found.append(("url", node))
            elif key in _B64_KEYS and len(node) > 64:
                raw = _b64_image(node)
                if raw:
                    found.append(("bytes", raw))
        elif isinstance(node, dict):
            for k, v in node.items():
                walk(v, str(k).lower())
        elif isinstance(node, list):
            for v in node:
                walk(v, key)

    walk(obj, None)
    seen: set[Any] = set()
    unique = []
    for kind, value in found:
        marker = value if kind == "url" else hash(value)
        if marker not in seen:
            seen.add(marker)
            unique.append((kind, value))
    return unique


class ImageService:
    def __init__(self, settings: Settings, upstream: GLMChatClient, fetcher: ImageFetcher) -> None:
        self.s = settings
        self.upstream = upstream
        self.fetcher = fetcher
        self.store = ImageStore(settings.image_cache_ttl, settings.image_cache_max)

    async def _post(self, body: dict[str, Any]) -> httpx.Response:
        nonce = await self.upstream.nonce()
        try:
            try:
                return await self.upstream.post_image(body, nonce)
            except NonceRejected:
                nonce = await self.upstream.nonce(refresh_from=nonce)
                return await self.upstream.post_image(body, nonce)
        except NonceRejected as exc:
            raise BridgeError("Upstream rejected the session (HTTP 403) for image generation", status=502,
                              code="upstream_auth_failed") from exc
        except httpx.TimeoutException as exc:
            raise BridgeError("Upstream image generation timed out", status=504, code="upstream_timeout") from exc
        except httpx.HTTPError as exc:
            raise BridgeError(f"Upstream connection failed: {exc.__class__.__name__}", status=502,
                              code="upstream_unreachable") from exc

    async def _generate_one(self, prompt: str, reference: str | None) -> list[tuple[str, Any]]:
        body: dict[str, Any] = {"prompt": prompt}
        if reference:
            body["image"] = reference
        resp = await self._post(body)
        if resp.status_code == 429:
            raise BridgeError(f"Upstream image limit: {describe_upstream_body(resp.text)}", status=429,
                              type="rate_limit_error", code="upstream_limit_reached")
        if resp.status_code != 200:
            raise BridgeError(f"Upstream image HTTP {resp.status_code}: {describe_upstream_body(resp.text)}",
                              status=502 if resp.status_code >= 500 else 400, code="upstream_image_failed")
        images = extract_images(resp)
        if not images:
            self.upstream.record_error("image: no image in response")
            raise BridgeError(f"Upstream returned no image: {describe_upstream_body(resp.text)}", status=502,
                              code="upstream_image_failed")
        return images

    async def generate(self, prompt: str, *, n: int, response_format: str | None, reference: str | None,
                       base_url: str) -> dict[str, Any]:
        if n > self.s.image_max_n:
            raise bad_request(f"n must be <= {self.s.image_max_n}", param="n")
        fmt = response_format or "url"
        if fmt not in ("url", "b64_json"):
            raise bad_request("response_format must be 'url' or 'b64_json'", param="response_format")
        ref = await self.fetcher.to_data_url(reference) if reference else None
        collected: list[tuple[str, Any]] = []
        while len(collected) < n:
            collected.extend(await self._generate_one(prompt, ref))
        data = []
        for kind, value in collected[:n]:
            if kind == "url" and fmt == "url":
                data.append({"url": value})
                continue
            raw = value if kind == "bytes" else await self.fetcher.fetch_bytes(value)
            mime = sniff_mime(raw) or "image/png"
            if fmt == "b64_json":
                data.append({"b64_json": base64.b64encode(raw).decode()})
            else:
                token = self.store.put(raw, mime)
                data.append({"url": f"{base_url}/v1/images/files/{token}"})
        return {"created": int(time.time()), "data": data}
